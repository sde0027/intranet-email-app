import fs from "node:fs";
import { fileTypeFromFile } from "file-type";

import { db } from "../../database/connection.js";
import { attachmentDirectory } from "./attachments.storage.js";

export class AttachmentServiceError extends Error {
  constructor(message, status, code) {
    super(message);
    this.name = "AttachmentServiceError";
    this.status = status;
    this.code = code;
  }
}

const allowedMimeTypes = new Set([
  "application/pdf",
  "image/jpeg",
  "image/png",
  "image/gif",
  "image/webp",
]);

// Validate the actual file signature, not just the supplied MIME type.
export async function validateUploadedFiles(files = []) {
  for (const file of files) {
    const detectedType = await fileTypeFromFile(file.path);

    if (
      !detectedType ||
      !allowedMimeTypes.has(detectedType.mime) ||
      detectedType.mime !== file.mimetype
    ) {
      throw new AttachmentServiceError(
        `Unsupported or invalid file: ${file.originalname}`,
        400,
        "INVALID_ATTACHMENT_TYPE",
      );
    }
  }
}

// Called inside the email sending database transaction.
export function insertAttachmentMetadata(emailId, files = []) {
  const insert = db.prepare(`
    INSERT INTO attachments (
      email_id,
      original_name,
      storage_name,
      mime_type,
      size_bytes
    )
    VALUES (?, ?, ?, ?, ?)
  `);

  for (const file of files) {
    insert.run(
      emailId,
      file.originalname
        .replace(/\\/g, "/")
        .split("/")
        .pop()
        .replace(/[\u0000-\u001f\u007f]/g, "")
        .slice(0, 255) || "attachment",
      file.filename,
      file.mimetype,
      file.size,
    );
  }
}

// Retrieve attachments only when the user can access the email.
export function getEmailAttachmentsService({ emailId, userId }) {
  const attachments = db
    .prepare(
      `
    SELECT
      a.id,
      a.original_name,
      a.mime_type,
      a.size_bytes,
      a.created_at
    FROM attachments a
    INNER JOIN emails e
      ON e.id = a.email_id
    WHERE e.id = ?
      AND e.status = 'SENT'
      AND (
        e.sender_id = ?
        OR EXISTS (
          SELECT 1
          FROM email_recipients er
          WHERE er.email_id = e.id
            AND er.recipient_id = ?
            AND er.is_deleted = 0
        )
      )
    ORDER BY a.id
  `,
    )
    .all(emailId, userId, userId);

  // Distinguish an inaccessible/nonexistent email from an email with no files.
  const accessibleEmail = db
    .prepare(
      `
    SELECT 1
    FROM emails e
    WHERE e.id = ?
      AND e.status = 'SENT'
      AND (
        e.sender_id = ?
        OR EXISTS (
          SELECT 1
          FROM email_recipients er
          WHERE er.email_id = e.id
            AND er.recipient_id = ?
            AND er.is_deleted = 0
        )
      )
  `,
    )
    .get(emailId, userId, userId);

  if (!accessibleEmail) {
    throw new AttachmentServiceError(
      "Email not found.",
      404,
      "EMAIL_NOT_FOUND",
    );
  }

  return attachments;
}

// Retrieve a download only if the user can access its parent email.
export function getAttachmentDownloadService({ attachmentId, userId }) {
  const attachment = db
    .prepare(
      `
    SELECT
      a.id,
      a.original_name,
      a.mime_type,
      a.size_bytes,
      a.storage_name
    FROM attachments a
    INNER JOIN emails e
      ON e.id = a.email_id
    WHERE a.id = ?
      AND e.status = 'SENT'
      AND (
        e.sender_id = ?
        OR EXISTS (
          SELECT 1
          FROM email_recipients er
          WHERE er.email_id = e.id
            AND er.recipient_id = ?
            AND er.is_deleted = 0
        )
      )
  `,
    )
    .get(attachmentId, userId, userId);

  if (!attachment) {
    throw new AttachmentServiceError(
      "Attachment not found.",
      404,
      "ATTACHMENT_NOT_FOUND",
    );
  }

  // storage_name is generated by the server, never supplied by the user.
  const filePath = path.join(attachmentDirectory, attachment.storage_name);

  if (!fs.existsSync(filePath)) {
    throw new AttachmentServiceError(
      "Attachment file is missing from storage.",
      404,
      "ATTACHMENT_FILE_MISSING",
    );
  }

  return {
    ...attachment,
    filePath,
  };
}

// Remove uploaded files if the corresponding email transaction fails.
export function cleanupUploadedFiles(files = []) {
  for (const file of files) {
    try {
      fs.unlinkSync(file.path);
    } catch {
      // Cleanup is best-effort.
    }
  }
}
